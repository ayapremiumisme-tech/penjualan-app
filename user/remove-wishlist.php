<?php

session_start();

/*
|--------------------------------------------------------------------------
| VALIDASI ID
|--------------------------------------------------------------------------
*/

if(
    !isset($_GET['id']) ||
    !is_numeric($_GET['id'])
){

    header("Location: wishlist.php");
    exit;
}

$id = intval($_GET['id']);

/*
|--------------------------------------------------------------------------
| CHECK WISHLIST
|--------------------------------------------------------------------------
*/

if(isset($_SESSION['wishlist'])){

    foreach($_SESSION['wishlist'] as $key => $item){

        if($item['id'] == $id){

            unset($_SESSION['wishlist'][$key]);

        }

    }

    /*
    |--------------------------------------------------------------------------
    | RESET ARRAY INDEX
    |--------------------------------------------------------------------------
    */

    $_SESSION['wishlist'] =
        array_values($_SESSION['wishlist']);

}

/*
|--------------------------------------------------------------------------
| SUCCESS MESSAGE
|--------------------------------------------------------------------------
*/

$_SESSION['success'] =
    "Produk berhasil dihapus dari wishlist";

/*
|--------------------------------------------------------------------------
| REDIRECT
|--------------------------------------------------------------------------
*/

header("Location: wishlist.php");
exit;